n1 = float(input("qual eh sua nota da primeira prova? "))
n2 = float(input("qual eh sua nota da segunda prova? "))
media = (n1 + n2) / 2
if media >= 6:
    print(f"Parabens, voce foi aprovado com media: {media:.1f}") 
else:
    print(f"Infelizmente voce foi reprovado com media: {media:.1f}")
